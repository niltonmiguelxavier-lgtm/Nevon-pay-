// Gera src/.generated/mockup-components.ts sem arrancar o Vite.
// Necessário para que `tsc`/`vite build` em CI funcionem num clone limpo:
// antes, o typecheck do workspace falhava por o módulo ainda não existir.
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import glob from "fast-glob";

const root = path.resolve(import.meta.dirname ?? path.dirname(new URL(import.meta.url).pathname));
const MOCKUPS_DIR = "src/components/mockups";
const GENERATED = "src/.generated/mockup-components.ts";

const files = await glob(`${MOCKUPS_DIR}/**/*.tsx`, { cwd: root, ignore: ["**/_*/**", "**/_*.tsx"] });

const entries = files
  .map((f) => ({ globKey: "./" + f.slice("src/".length), importPath: path.posix.relative("src/.generated", f) }))
  .map((c) => `  ${JSON.stringify(c.globKey)}: () => import(${JSON.stringify(c.importPath)})`)
  .join(",\n");

const source = [
  "// This file is auto-generated by mockupPreviewPlugin.ts.",
  "type ModuleMap = Record<string, () => Promise<Record<string, unknown>>>;",
  "export const modules: ModuleMap = {",
  entries,
  "};",
  "",
].join("\n");

const target = path.join(root, GENERATED);
mkdirSync(path.dirname(target), { recursive: true });
writeFileSync(target, source);
console.log(`[mockup-sandbox] ${files.length} mockups → ${GENERATED}`);
